for t in ['(1) 참고자료의 불평등 사례(A~I) 중 하나를 고르거나, 다른 사례를 직접 정합니다.',
          '(2) 수행평가지의 <조건>에 맞추어 서론-본론-결론의 글을 씁니다.',
          '(3) 빠진 내용이 없는지 확인한 뒤 수행평가지를 제출합니다.']:
    p(t, size=9)

h('4. 채점기준표 (10점)')
grid([1], [[c([f'{i + 1}. {t}' for i, t in enumerate(CRITS)], size=9)]])
scores = [('7개', '10점'), ('6개', '9점'), ('5개', '8점'), ('4개', '7점'), ('3개', '6점'),
          ('2개', '5점'), ('1개', '4점'), ('0개·미제출', '3점')]
