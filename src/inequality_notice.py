import json
import content as C
from content import title, h, p, grid, c, hc, BLUE, YEL

C.blocks.clear()
blocks = C.blocks

CRITS = [
    '사회 및 공간 불평등 사례 하나를 골라 현황을 서술하였다.',
    '해당 불평등이 나타나는 원인을 제시하였다.',
    '자유주의·공동체주의 정의관의 입장을 사례에 적용하였다.',
    '두 정의관 중 자신의 입장을 정하고 이유를 서술하였다.',
    '정의로운 사회를 위한 제도적 방안 또는 실천 방안을 한 가지 제안하였다.',
    '서론–본론–결론의 형식을 갖추어 작성하였다.',
    '결론 부분에 자신이 느낀 바나 소감을 작성하였다.',
]

title('1학년 통합사회 수행평가 실시 안내', '사회 불평등 사례 분석·논술하기')

p('통합사회 수업 시간에 아래와 같이 수행평가를 실시합니다. 내용을 미리 읽고 준비해 주세요.', size=9.5, before=2, after=4)

h('1. 평가 개요')
grid([1.6, 8.4], [
    [hc('평가 내용', fill=None), c('우리 사회의 불평등 사례 하나를 골라 현황과 원인을 분석하고, 자유주의·공동체주의 정의관을 적용하여 '
                                 '나의 입장과 해결 방안을 서론-본론-결론의 논술문으로 쓴다.', size=9)],
    [hc('평가 방법', fill=None), c('서술·논술, 교사 관찰 및 기록 (수업 1차시 안에 작성하여 제출)', size=9)],
    [hc('배점', fill=None), c('10점', size=9)],
    [hc('준비물', fill=None), c('필기구 (수행평가지와 참고자료는 당일 나누어 줍니다)', size=9)],
])

