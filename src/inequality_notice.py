for t in ['손으로 작성하며, 작성 중에는 휴대폰·태블릿·노트북을 사용하지 않습니다.',
          '참고자료의 수치와 내용은 활용해도 됩니다. 다만 다른 사람의 글을 베끼면 안 됩니다.',
          '수업 시간 안에 작성하여 수행평가지만 제출합니다. 참고자료는 제출하지 않습니다.']:
    p('· ' + t, size=9)

