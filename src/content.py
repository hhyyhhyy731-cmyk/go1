def writing(head, guide_title, guide_lines, crit_lines, n, sign, extra=None):
    grid([1], [[c([dict(t=guide_title, size=9, bold=True)] + [dict(t=t, size=8.5) for t in guide_lines]
                  + [dict(t=crit_lines, size=8.5, bold=True, color='1F4E79')], fill='F2F2F2')]])
    p(' ', size=4)
    blocks.append(dict(k='lined', head=head, n=n, h=9.5, crit_w=13))
    p(sign, align='right', before=2)
    if extra:
        p(extra, bold=True, size=12, align='center')

