blocks = []
def title(t, sub=None): blocks.append(dict(k='title', t=t, sub=sub))
def h(t): blocks.append(dict(k='h', t=t))
def p(t, **f): blocks.append(dict(k='p', t=t, **f))
def name(): blocks.append(dict(k='name'))
def brk(): blocks.append(dict(k='brk'))
def form(rows): blocks.append(dict(k='form', rows=[dict(label=l, guide=g, h=hh) for l, g, hh in rows]))
def grid(widths, rows): blocks.append(dict(k='grid', widths=widths, rows=rows))
def c(lines, **o): return dict(lines=lines if isinstance(lines, list) else [lines], **o)
def hc(t, fill=GRAY): return c(t, fill=fill, bold=True, align='center')
def g(t): return dict(t=t, **GUIDE)

