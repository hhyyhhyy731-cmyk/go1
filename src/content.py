"""수행평가 양식 내용 정의 — docx(build.js)와 hwpx(build_hwpx.py)가 함께 쓴다.

블록 종류
  title(text, sub) / h(text) / p(text, **fmt) / name / brk
  form(rows=[(label, guide, height_mm)])          라벨 | 쓰기칸
  grid(widths=[비율...], rows=[[cell, ...], ...]) 일반 표
cell = dict(lines=[str | {t, size, color, bold, italic}], fill, bold, align, size, h(mm), top)
"""
